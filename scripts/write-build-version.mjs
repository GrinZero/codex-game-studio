import { readFileSync, writeFileSync } from "node:fs";

const { version } = JSON.parse(readFileSync("package.json", "utf8"));
const builtAt = new Date();
const parts = new Intl.DateTimeFormat("en-GB", {
  timeZone: "Asia/Taipei",
  year: "numeric",
  month: "2-digit",
  day: "2-digit",
  hour: "2-digit",
  minute: "2-digit",
  second: "2-digit",
  hourCycle: "h23",
}).formatToParts(builtAt);
const stamp = ["year", "month", "day", "hour", "minute", "second"]
  .map((type) => parts.find((part) => part.type === type).value)
  .join("");
writeFileSync(
  "src/shared/version.ts",
  `// Generated by npm run build. Timezone: Asia/Taipei.\nexport const studioVersion = ${JSON.stringify(version)};\nexport const studioBuildTimestamp = ${JSON.stringify(stamp)};\nexport const studioVersionMarker = ${JSON.stringify(`v${version}-${stamp}`)};\nexport const studioBuiltAt = ${JSON.stringify(builtAt.toISOString())};\n`,
);
console.log(`Workbench version: v${version}-${stamp}`);
